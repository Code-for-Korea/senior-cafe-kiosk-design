import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import ts from 'typescript'
const source = readFileSync(new URL('../src/inactivityTimer.ts', import.meta.url), 'utf8')
const { outputText } = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2022 } })
const { InactivityTimer } = await import('data:text/javascript;base64,' + Buffer.from(outputText).toString('base64'))
const timer = new InactivityTimer(0)
assert.equal(timer.poll(89999), null)
assert.equal(timer.poll(90000), 30)
assert.equal(timer.poll(100000), 20)
// 경고 중 배경 터치/휠은 계속 주문하기를 대신하지 않는다.
timer.activity(110000)
assert.equal(timer.poll(120000), 0)
timer.reset(120000)
assert.equal(timer.poll(209999), null)
timer.activity(200000)
assert.equal(timer.poll(289999), null)
assert.equal(timer.poll(290000), 30)
// 직원 요청/대기와 숨긴 탭은 초기화를 중단한다. 복귀 후에는 새 90초.
timer.pause()
assert.equal(timer.poll(900000), null)
timer.resume(900000)
assert.equal(timer.poll(989999), null)
assert.equal(timer.poll(990000), 30)
// 타이머 실행이 늦어져도 사용자에게 경고를 읽을 30초를 보장한다.
const delayed = new InactivityTimer(0)
assert.equal(delayed.poll(500000), 30)
assert.equal(delayed.poll(529999), 1)
assert.equal(delayed.poll(530000), 0)
const preview = new InactivityTimer(0, true)
assert.equal(preview.poll(0), 30)
assert.equal(preview.poll(30000), 0)
console.log('Inactivity checks passed: 90+30 seconds, activity, resume, pause, delayed warning, expiry.')

const staffSource = readFileSync(new URL('../src/staffCall.ts', import.meta.url), 'utf8')
const staffOutput = ts.transpileModule(staffSource, { compilerOptions: { module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2022 } }).outputText
const { staffCallReducer: transition, initialStaffCall, staffCallPausesInactivity: pauses } = await import('data:text/javascript;base64,' + Buffer.from(staffOutput).toString('base64'))
let staff = transition(initialStaffCall, 'open')
// 부르기 전 확인 창은 멈추지 않는다. 연 채 떠나도 첫 화면으로 돌아간다(사용자 2026-10-21).
assert.equal(pauses(staff), false, 'The confirm dialog left open does not hold the screen')
staff = transition(staff, 'close')
assert.equal(staff.pending, false)
assert.equal(pauses(staff), false)
staff = transition(transition(staff, 'open'), 'request')
assert.equal(staff.dialog, 'waiting')
// 모달을 닫아도 호출 대기와 타이머 정지를 유지한다.
staff = transition(staff, 'close')
assert.deepEqual(staff, { pending: true, late: false, dialog: null })
assert.equal(pauses(staff), true)
const waitingTimer = new InactivityTimer(0)
if (pauses(staff)) waitingTimer.pause()
assert.equal(waitingTimer.poll(600000), null)
staff = transition(staff, 'open')
assert.equal(staff.dialog, 'waiting')
staff = transition(staff, 'askCancel')
assert.equal(staff.pending, true)
assert.equal(staff.dialog, 'cancel')
staff = transition(staff, 'open') // 계속 기다리기
assert.equal(staff.dialog, 'waiting')
assert.equal(staff.pending, true)
staff = transition(transition(staff, 'askCancel'), 'cancel')
assert.deepEqual(staff, initialStaffCall)
assert.equal(pauses(staff), false)
waitingTimer.resume(600000)
assert.equal(waitingTimer.poll(689999), null)
assert.equal(waitingTimer.poll(690000), 30)
assert.deepEqual(transition(transition(initialStaffCall, 'request'), 'reset'), initialStaffCall)
// 부른 지 오래됨(기획 G01-LATE): 창은 그대로 두고 late만 켠다. 다시 부르면 풀리고, 끝나면 처음으로.
let late = transition(transition(transition(initialStaffCall, 'request'), 'close'), 'late')
assert.deepEqual(late, { pending: true, late: true, dialog: null }, 'Being late does not open a dialog by itself')
// 늦어지면 손님이 카운터로 갈 수 있어 다시 센다. 늦음 창(waiting)·취소 확인 창이 열려 있어도(사용자 2026-10-21 가안).
assert.equal(pauses(late), false, 'A late call lets the timeout run again')
assert.equal(pauses(transition(late, 'open')), false, 'The late dialog left open does not hold the screen')
assert.equal(pauses(transition(late, 'askCancel')), false)
assert.equal(pauses(transition(late, 'request')), true, 'Calling again pauses while staff is on the way')
const lateTimer = new InactivityTimer(0)
lateTimer.pause()
lateTimer.resume(90000) // 늦어진 때부터
assert.equal(lateTimer.poll(179999), null)
assert.equal(lateTimer.poll(180000), 30, 'The usual warning comes 90 seconds after the call is late')
assert.equal(transition(late, 'open').dialog, 'waiting')
assert.deepEqual(transition(late, 'request'), { pending: true, late: false, dialog: 'waiting' }, 'Calling again starts the wait over')
assert.deepEqual(transition(initialStaffCall, 'late'), initialStaffCall, 'No call, nothing is late')
assert.deepEqual(transition(late, 'reset'), initialStaffCall)
console.log('Staff call checks passed: close/reopen retains request, explicit cancellation, timer pause/resume, session reset, late and call again.')
